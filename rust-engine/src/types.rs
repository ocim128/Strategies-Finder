/// A completed trade with entry and exit information
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Trade {
    pub id: u32,
    #[serde(rename = "type")]
    pub trade_type: TradeType,
    #[serde(rename = "entryTime")]
    pub entry_time: Time,
    #[serde(rename = "entryPrice")]
    pub entry_price: f64,
    #[serde(rename = "exitTime")]
    pub exit_time: Time,
    #[serde(rename = "exitPrice")]
    pub exit_price: f64,
    pub pnl: f64,
    #[serde(rename = "pnlPercent")]
    pub pnl_percent: f64,
    pub size: f64,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub fees: Option<f64>,
}
#[allow(dead_code)]
impl Trade {
    /// Check if this trade was profitable
    #[inline]
    #[must_use]
    pub const fn is_winner(&self) -> bool {
        self.pnl > 0.0
    }
    /// Get the R-multiple (return / risk)
    #[inline]
    #[must_use]
    pub fn r_multiple(&self, risk_per_share: f64) -> f64 {
        if risk_per_share == 0.0 {
            return 0.0;
        }
        self.pnl / (self.size * risk_per_share)
    }
}
