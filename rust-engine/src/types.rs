/// OHLCV (Open, High, Low, Close, Volume) candle data
///
/// Memory-optimized layout for cache efficiency with 5M+ bars
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
#[repr(C)]
#[allow(clippy::upper_case_acronyms)]
pub struct OHLCV {
    pub time: Time,
    pub open: f64,
    pub high: f64,
    pub low: f64,
    pub close: f64,
    pub volume: f64,
}
#[allow(dead_code)]
impl OHLCV {
    #[inline]
    #[must_use]
    pub const fn new(time: Time, open: f64, high: f64, low: f64, close: f64, volume: f64) -> Self {
        Self {
            time,
            open,
            high,
            low,
            close,
            volume,
        }
    }
    /// Typical price: (high + low + close) / 3
    #[inline]
    #[must_use]
    pub fn typical_price(&self) -> f64 {
        (self.high + self.low + self.close) / 3.0
    }
    /// HL2: (high + low) / 2
    #[inline]
    #[must_use]
    pub fn hl2(&self) -> f64 {
        (self.high + self.low) / 2.0
    }
}
